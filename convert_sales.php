$lines = preg_split('/\r\n|\r|\n/', $raw);
$count = 0;
$out = [];
$seen = [];

foreach ($lines as $line) {
    $line = trim($line);
    if (empty($line)) continue;

    // Match with state: [XX] DomainName (ST|ST2) $price
    if (preg_match('/^\[.*?\]\s+(\S+)\s+\(([^)]*)\)\s+\$(\d[\d,]*)/', $line, $m)) {
        $rawDomain = trim($m[1]);
        $statePart = trim($m[2]);
        $price = (int) str_replace(',', '', $m[3] ?? '0');
    }
    // Match without state: [XX] DomainName $price
    elseif (preg_match('/^\[.*?\]\s+(\S+)\s+\$(\d[\d,]*)/', $line, $m)) {
        $rawDomain = trim($m[1]);
        $statePart = '';
        $price = (int) str_replace(',', '', $m[2] ?? '0');
    } else {
        continue;
    }

    $base = preg_replace('/\.(com|net|org|co|io|us)$/', '', $rawDomain);
    $baseClean = preg_replace('/[^a-zA-Z]/', '', $base);
    if (str_ends_with($rawDomain, '.net')) {
        $domain = strtolower($base) . '.net';
    } else {
        $domain = strtolower($base) . '.com';
    }

    if (isset($seen[$domain])) continue;
    $seen[$domain] = true;

    $states = array_map('trim', explode('|', $statePart));
    $stateCode = $states[0] ?? '';
    $stateFull = $stateMap[$stateCode][0] ?? $stateCode;
    $country = $stateMap[$stateCode][1] ?? 'United States';

    if (isset($cityMap[$baseClean])) {
        $city = $cityMap[$baseClean][0];
        $keyword = $cityMap[$baseClean][1];
    } else {
        $city = $stateFull;
        $keyword = preg_replace('/([a-z])([A-Z])/', '$1 $2', $baseClean);
        $keyword = preg_replace('/\b[A-Z]{2,}\b/', '$0', $keyword);
        $keyword = trim($keyword);
    }

    $count++;
    $out[] = "{$domain},{$keyword},{$price},{$city},{$stateFull},{$country}";
}

