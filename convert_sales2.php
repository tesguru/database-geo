$lines = preg_split('/\r\n|\r|\n/', $raw);
$out = [];
$seen = [];
$errors = [];
$skippedNoPrice = [];
$count = 0;

foreach ($lines as $line) {
    $line = trim($line);
    if (empty($line)) continue;

    $tokens = preg_split('/\s+/', $line);
    $tokens = array_values(array_filter($tokens, fn ($t) => $t !== ''));

    // domain = last token
    $rawDomain = $tokens[count($tokens) - 1];
    // find price token (starts with $ or €)
    $priceIdx = null;
    foreach ($tokens as $i => $t) {
        if (preg_match('/^[€$]/', $t) && preg_match('/[\d.]+/', $t)) {
            $priceIdx = $i;
            break;
        }
    }
    if ($priceIdx === null) {
        $skippedNoPrice[] = $rawDomain;
        continue;
    }

    $priceToken = $tokens[$priceIdx];
    $isEuro = str_starts_with($priceToken, '€');
    $amount = (float) preg_replace('/[^0-9.]/', '', $priceToken);
    if ($isEuro) $amount = round($amount * 1.1);

    // clean domain
    $domain = strtolower(trim($rawDomain));
    $domain = ltrim($domain, '* ');
    $domain = rtrim($domain, '.');
    $base = preg_replace('/\.(com|net|org|co|io|us|ca|uk)$/', '', $domain);
    $baseClean = preg_replace('/[^a-z]/', '', $base);
    $domain .= '.com';

    if (isset($seen[$domain])) continue;
    $seen[$domain] = true;

    if (!isset($data[$baseClean])) {
        $errors[] = "Unmapped domain: {$domain} ({$baseClean})";
        continue;
    }

    [$city, $keyword, $state, $country] = $data[$baseClean];

    $count++;
    $out[] = "{$domain},{$keyword},{$amount},{$city},{$state},{$country}";
}

echo "=== TOTAL: {$count} records ===\n\n";
if (!empty($skippedNoPrice)) {
    echo "Skipped (no price): " . count($skippedNoPrice) . " -> " . implode(', ', $skippedNoPrice) . "\n\n";
}
if (!empty($errors)) {
    echo "ERRORS: " . count($errors) . "\n" . implode("\n", $errors) . "\n\n";
}

$csv = implode("\n", $out);

